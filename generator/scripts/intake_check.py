REQUIRED_FIELDS = ["机构名称", "治理", "部门", "员工总数", "业务安排", "集团化", "特殊业务"]


def get(cfg, path, default=None):
    """按 (section, key[, expect]) 取值，支持嵌套一层"""
    cur = cfg
    for k in path[:-1]:
        if not isinstance(cur, dict) or k not in cur:
            return default
        cur = cur[k]
    if not isinstance(cur, dict):
        return default
    return cur.get(path[-1], default)


def check(cfg):
    """校验输入，返回 (errors, warnings)"""
    errors, warnings = [], []

    for f in REQUIRED_FIELDS:
        if f not in cfg or cfg[f] in (None, "", []):
            errors.append(f"缺少必填字段：{f}")

    gov = cfg.get("治理", {}) or {}
    if not gov.get("合规风控负责人"):
        errors.append("未设置合规风控负责人 —— 违反《内控指引》第十二条（必须设置负责合规风控的高级管理人员）")

    n_exec = gov.get("高管人数")
    if isinstance(n_exec, int) and n_exec < 2:
        errors.append(f"高管人数 {n_exec} 人 < 2 —— 违反《内控指引》第十一条第二款（至少 2 名高级管理人员）")

    if gov.get("合规风控负责人兼任投资职务") is True:
        warnings.append("合规风控负责人兼任投资职务 —— 与《内控指引》第十二条独立性要求存在张力，制度中须作专项安排并提示")

    staff = cfg.get("专职员工数")
    if isinstance(staff, int) and staff < 5:
        warnings.append(f"专职员工 {staff} 人 < 5 —— 不满足《登记备案办法》第八条第一款第四项（专职员工不少于 5 人）。"
                        f"注：本项为管理人登记要求，制度本身无直接条文，但须在待确认事项中列出")

    if cfg.get("投资经理与交易员同一人") is True:
        warnings.append("投资经理与交易员为同一人 —— 不满足《内控指引》第十条相互制约、第十四条岗位分设要求，制度中须说明替代控制措施")

    # 法律风险提示
    risks = []
    if get(cfg, ("业务安排", "委托募集")) is True:
        risks.append(
            '【委托募集】已选委托募集。《私募条例》第十七条（行政法规）规定「应当自行募集资金，不得委托他人募集资金」，'
            '与《内控指引》第十七条冲突，按上位法优先以《私募条例》为准。'
            '罚则：《私募条例》第四十八条，没收违法所得并处 1-5 倍罚款；无违法所得或不足 100 万元的，并处 10 万-100 万元。'
            '制度主文须写自行募集；代销安排须单列并标「⚠️ 待核实」，文末提示风险。'
        )
    if get(cfg, ("集团化", "同一实控人控制两家以上管理人")) is True:
        risks.append("【集团化】需按《登记备案办法》第十七条、第十八条建立集团化持续合规与风险管理体系（模块 26）")
    if get(cfg, ("集团化", "实控人为上市公司")) is True:
        risks.append("【实控人为上市公司】需按《登记指引2号》第三条建立业务隔离制度（⚠️ 该条原文待核实后方可落脚注）")
    if get(cfg, ("特殊业务", "期权等场内衍生品")) is True:
        risks.append(
            '【场内衍生品】同一资产认定口径：《运作指引》第四十一条第（九）项第 5 目——'
            '标准化期货和衍生品类资产按照单只期货或者期权合约视为同一资产'
            '（即每一张期权合约各自为一个「同一资产」，不按品种整体合并计算）。'
            '另：《运作指引》第十七条仅规范场外衍生品，场内期权不适用该条，'
            '但仍受第十二条双 25%、第十五条 200% 杠杆约束。'
            '交易所层面持仓限额须另行核交易所规则，不在《运作指引》范围内。'
        )
    if get(cfg, ("特殊业务", "场外衍生品")) is True:
        risks.append(
            "【场外衍生品】须核对《运作指引》第十七条门槛：场外期权需基金净资产不低于 5000 万元；"
            "保证金+权利金合计不得超过基金净资产 25%；雪球结构合约名义本金不得超过基金净资产 25%"
        )

    # 待确认事项
    todos = []
    if get(cfg, ("业务安排", "委托募集")) is True:
        todos.append('核实证监会是否已就「委托他人募集」作出《私募条例》第十七条的例外规定')
    todos.append("证监会令第233号《私募投资基金信息披露监督管理办法》是否已替代旧信息披露办法 —— 需核实后再落模块 13 脚注")
    todos.append('《运作指引》第三十五条、第三十七条「符合一定资产管理规模以上等条件」的具体门槛由协会另行规定，尚未明确')
    todos.append("模块 27（反洗钱）专项规定尚未录入原文库，生成时须先补原文或标注待核实")
    todos.append("《基金法》《私募投资基金监督管理暂行办法》（证监会令第105号）条文尚未录入原文库")

    return errors, warnings, risks, todos


def select(cfg):
    """按触发条件选定模块，返回 [(编号, 名称, 类型, 依据)]"""
    picked = []
    for no, name, kind, basis, trig in MODULES:
        if trig is None:
            picked.append((no, name, kind, basis))
            continue
        if len(trig) == 2:
            section, key = trig
            if get(cfg, (section, key)) is True:
                picked.append((no, name, kind, basis))
        elif len(trig) == 3:
            # 三元组：(section, key, expect) —— 当该字段值等于 expect 时触发
            section, key, expect = trig
            if get(cfg, (section, key)) is expect:
                picked.append((no, name, kind, basis))
    return picked


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)

    path = sys.argv[1]
    with open(path, "r", encoding="utf-8") as f:
        cfg = json.load(f)

    errors, warnings, risks, todos = check(cfg)
    picked = select(cfg)

    if "--json" in sys.argv:
        print(json.dumps({
            "errors": errors, "warnings": warnings, "risks": risks,
            "todos": todos,
            "modules": [{"no": n, "name": nm, "kind": k, "basis": b} for n, nm, k, b in picked],
        }, ensure_ascii=False, indent=2))
        return

    print("=" * 70)
    print("制度模块选型报告")
    print("机构：" + str(cfg.get("机构名称", "(未填写)")))
    print("=" * 70)

    if errors:
        print("\n【错误 · 必须修正后才能生成】")
        for e in errors:
            print("  ✗ " + e)
    else:
        print("\n【校验】通过，无阻断性错误")

    if warnings:
        print("\n【警告 · 需在制度中作专项安排】")
        for w in warnings:
            print("  ! " + w)

    if risks:
        print("\n【法律风险提示 · 生成时必须处理】")
        for i, r in enumerate(risks, 1):
            print(f"  {i}. {r}")

    n_req = sum(1 for _, _, k, _ in picked if k == "必建")
    n_trg = sum(1 for _, _, k, _ in picked if k == "触发")
    n_opt = sum(1 for _, _, k, _ in picked if k == "选建")
    print(f"\n【应建制度】共 {len(picked)} 份（必建 {n_req} / 触发 {n_trg} / 选建 {n_opt}）")
    for no, name, kind, basis in picked:
        print(f"\n  [{no}] {name}  <{kind}>")
        print(f"      依据：{basis}")

    print("\n【待确认事项 · 必须写入制度文末】")
    for i, t in enumerate(todos, 1):
        print(f"  {i}. {t}")

    print("\n" + "=" * 70)
    print("下一步：按上表逐份生成，依据见 references/02-制度模块与法规映射表.md；")
    print("每条脚注须回 references/01（分册索引）取原文，禁止凭记忆落条号。")
    print("=" * 70)


if __name__ == "__main__":
    main()
